CREATE TABLE first_sats_invitations (
    id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    public_id CHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    locale CHAR(2) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    inviter_label VARCHAR(50) NOT NULL,
    invitee_label VARCHAR(50) NOT NULL,
    personal_message VARCHAR(500) NULL,
    sats_amount INT UNSIGNED NOT NULL,
    chf_rate DECIMAL(18, 2) NULL,
    chf_rate_fetched_at DATETIME(6) NULL,
    invitation_access_digest BINARY(32) NOT NULL,
    invitation_access_version INT UNSIGNED NOT NULL DEFAULT 1,
    management_access_digest BINARY(32) NOT NULL,
    management_access_version INT UNSIGNED NOT NULL DEFAULT 1,
    recovery_digest BINARY(32) NOT NULL,
    recovery_version INT UNSIGNED NOT NULL DEFAULT 1,
    status ENUM('open', 'accepted', 'revoked', 'expired') NOT NULL DEFAULT 'open',
    inviter_adult_attested TINYINT(1) NOT NULL,
    inviter_terms_version VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    inviter_terms_accepted_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    accept_until DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    delete_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_first_sats_public_id (public_id),
    KEY ix_first_sats_accept_until (accept_until),
    KEY ix_first_sats_delete_at (delete_at),
    CONSTRAINT chk_first_sats_sats_amount CHECK (sats_amount <= 100000),
    CONSTRAINT chk_first_sats_locale CHECK (locale IN ('de', 'fr', 'it', 'rm')),
    CONSTRAINT chk_first_sats_inviter_adult CHECK (inviter_adult_attested = 1),
    CONSTRAINT chk_first_sats_accept_until CHECK (accept_until > created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
